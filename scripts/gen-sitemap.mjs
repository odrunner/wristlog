// Regenerates, from the same model list:
//   1. sitemap.xml — four static pages + one /w/<slug>/ entry per
//      content-bearing canonical watch model (description + hero image —
//      thin stubs stay out of Google on purpose)
//   2. w/all/index.html — the static, crawlable model hub (crawl graph +
//      internal PageRank; GSC 2026-10 showed sitemap-only discovery fails)
//   3. w/<slug>/index.html — a static PRERENDERED snapshot per model
//      (added 2026-11-08). The dynamic /w/?m= page serves crawlers an empty
//      "Loading…" shell, which is why WRotate had zero search presence; the
//      snapshot bakes the real page markup (rendered by model-page.js itself,
//      in Node, with the exact ctx the live page uses) plus title, meta
//      description, canonical and og tags. Client-side JS then re-renders
//      from the embedded data (interactivity) and refreshes from the live
//      RPCs. /w/?m=<slug> keeps working and canonicalizes to /w/<slug>/.
//      PRIVACY: baked snapshots carry NO member content — owners' names,
//      avatars and wrist-shot photos are stripped from the committed HTML
//      and only appear after the live refresh. A public git repo must not
//      freeze member data into history.
//
// Re-run after enriching models, then commit the diff; all outputs are under
// SITE_FILES (w/ is copied recursively) so the deploy picks them up.
//
//   node scripts/gen-sitemap.mjs
//
// Reads the model list from the production DB via `supabase db query --linked`
// (needs SUPABASE_ACCESS_TOKEN, loaded by .zshrc from ~/.config/supabase/env)
// and each model's page data via the same public PostgREST RPCs the live page
// calls (anon key, read-only — equivalent to ~111 page views).
