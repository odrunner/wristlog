#!/usr/bin/env node
// Regenerates sitemap.xml AND the static model hub page w/all/index.html from
// the same query: the four static pages plus one /w/?m=<slug> entry per
// content-bearing canonical watch model (description + hero image — thin
// stubs stay out of Google on purpose). The hub exists for crawl discovery:
// GSC 2026-10 showed all model pages "Discovered - currently not indexed"
// (never crawled) because the sitemap was their only discovery path — plain
// <a href> links give Google a crawl graph and the pages internal PageRank.
// Re-run after enriching models, then commit the diff; both outputs are under
// SITE_FILES so the deploy picks them up.
//
//   node scripts/gen-sitemap.mjs
//
// Reads the production DB via `supabase db query --linked` (needs
// SUPABASE_ACCESS_TOKEN, loaded by .zshrc from ~/.config/supabase/env).
import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dsHash } from './ds-stamp.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const SQL = `SELECT slug, brand, name,
    GREATEST(created_at, COALESCE(enriched_at, created_at))::date AS lastmod
  FROM watch_models
  WHERE merged_into IS NULL AND description IS NOT NULL AND hero_image IS NOT NULL
  ORDER BY brand, name`;

const raw = execFileSync('npx', ['supabase', 'db', 'query', '--linked', SQL], {
  cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'],
});
const rows = (JSON.parse(raw.slice(raw.indexOf('{'))).rows || [])
  .filter(r => /^[a-z0-9-]+$/.test(r.slug || '') && r.brand && r.name);
if (rows.length < 50) {
  throw new Error(`only ${rows.length} model rows came back — refusing to shrink the sitemap (expected 100+)`);
}

// ── sitemap.xml ──
const url = (loc, changefreq, priority, lastmod) =>
  `  <url>\n    <loc>${loc}</loc>${lastmod ? `\n    <lastmod>${lastmod}</lastmod>` : ''}\n    <changefreq>${changefreq}</changefreq>\n    <priority>${priority}</priority>\n  </url>`;

const bySlug = [...rows].sort((a, b) => a.slug.localeCompare(b.slug));
const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  url('https://wrotate.com/', 'weekly', '1.0'),
  url('https://wrotate.com/privacy.html', 'yearly', '0.3'),
  url('https://wrotate.com/terms.html', 'yearly', '0.3'),
  url('https://wrotate.com/profile/', 'daily', '0.7'),
  url('https://wrotate.com/w/all/', 'weekly', '0.7'),
  ...bySlug.map(r => url(`https://wrotate.com/w/?m=${r.slug}`, 'monthly', '0.6', r.lastmod)),
  '</urlset>',
  '',
].join('\n');
writeFileSync(join(root, 'sitemap.xml'), xml);

// ── w/all/index.html — the static, crawlable model hub ──
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const brands = new Map();
for (const r of rows) {
  if (!brands.has(r.brand)) brands.set(r.brand, []);
  brands.get(r.brand).push(r);
}
const sections = [...brands.entries()].map(([brand, models]) => `    <section>
      <h2>${esc(brand)}</h2>
      <ul>
${models.map(m => `        <li><a href="/w/?m=${m.slug}">${esc(m.name)}</a></li>`).join('\n')}
      </ul>
    </section>`).join('\n');

const hub = `<!DOCTYPE html>
<!-- GENERATED by scripts/gen-sitemap.mjs — do not hand-edit; re-run it instead. -->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
  <meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self'; object-src 'none'; base-uri 'self';">
  <title>All Watch Models — WRotate</title>
  <meta name="description" content="Browse every watch model on WRotate: real-world accuracy measurements, owners and wear stats for ${rows.length} models from ${brands.size} brands.">
  <meta name="robots" content="index, follow">
  <link rel="icon" type="image/svg+xml" href="/icon.svg">
  <link rel="canonical" href="https://wrotate.com/w/all/">
  <script>
    (function(){
      try {
        const stored = localStorage.getItem('wrotate_theme');
        const prefer = stored || (window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light');
        if (prefer === 'dark') document.documentElement.setAttribute('data-theme', 'dark');
      } catch(e) {}
    })();
  </script>
  <link rel="stylesheet" href="/design-system.css?v=${dsHash()}">
  <style>
    *, *::before, *::after { box-sizing: border-box; margin: 0; padding: 0; }
    body { background: var(--bg); color: var(--text); font-family: var(--font-sans); min-height: 100vh; -webkit-font-smoothing: antialiased; }
    #page { max-width: var(--size-120); margin: 0 auto; padding: var(--space-8) var(--space-5) var(--space-12); }
    h1 { font-size: var(--fs-2xl); font-weight: var(--fw-semibold); letter-spacing: var(--ls-display); line-height: var(--lh-tight); }
    header p { color: var(--muted); font-size: var(--fs-md); margin-top: var(--space-2); }
    section { margin-top: var(--space-8); }
    h2 { font-size: var(--fs-xl); font-weight: var(--fw-semibold); line-height: var(--lh-tight); margin-bottom: var(--space-3); }
    ul { list-style: none; }
    li { margin-top: var(--space-2); }
    a { color: var(--gold-lt); text-decoration: none; font-size: var(--fs-md); }
    a:hover { text-decoration: underline; }
    footer { margin-top: var(--space-12); padding-top: var(--space-6); border-top: 1px solid var(--border); color: var(--muted); font-size: var(--fs-sm); }
  </style>
</head>
<body>
  <div id="page">
    <header>
      <h1>Watch models on WRotate</h1>
      <p>${rows.length} models from ${brands.size} brands, with real-world accuracy measurements and owner stats from the WRotate community.</p>
    </header>
    <main>
${sections}
    </main>
    <footer><a href="https://wrotate.com">WRotate</a> — track your watch collection and measure its accuracy.</footer>
  </div>
</body>
</html>
`;
mkdirSync(join(root, 'w', 'all'), { recursive: true });
writeFileSync(join(root, 'w', 'all', 'index.html'), hub);
console.log(`sitemap.xml written: 5 static pages + ${rows.length} model pages · w/all/index.html written (${brands.size} brands)`);
