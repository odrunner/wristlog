// ── w/<slug>/index.html — prerendered model snapshots ──

// model-page.js is window-scoped; run it against a throwaway shim so the
// REAL renderer produces the baked markup (zero template duplication).
function loadRenderer() {
  const src = readFileSync(join(root, 'model-page.js'), 'utf8');
  const noop = () => {};
  const docShim = { addEventListener: noop, getElementById: () => null, createElement: () => ({}), head: { appendChild: noop } };
  const win = {};
  new Function('window', 'document', 'requestAnimationFrame', src)(win, docShim, noop);
  if (!win.WRModelPage || !win.WRModelPage.css) throw new Error('model-page.js did not expose WRModelPage.css');
  return win.WRModelPage;
}
const MP = loadRenderer();

async function rpc(name, args) {
  const res = await fetch(`${API}/rest/v1/rpc/${name}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', apikey: KEY, Authorization: `Bearer ${KEY}` },
    body: JSON.stringify(args),
  });
  if (!res.ok) throw new Error(`${name} ${res.status}: ${(await res.text()).slice(0, 200)}`);
  return res.json();
}

function metaDescription(m, totalOwners, acc) {
  const stats = [];
  if (acc && acc.med != null) stats.push(`median ${MP.fmtRate(acc.med)} from ${acc.n_members} members' timegrapher measurements`);
  if (totalOwners) stats.push(`${totalOwners} owner${totalOwners === 1 ? '' : 's'} on WRotate`);
  const lead = `${m.brand} ${m.name}: real-world accuracy${stats.length ? ` — ${stats.join(', ')}` : ' and owners on WRotate'}.`;
  const excerpt = String(m.description || '').trim();
  let out = excerpt ? `${lead} ${excerpt}` : lead;
  if (out.length > 300) out = out.slice(0, 299).replace(/\s+\S*$/, '') + '…';
  return out;
}

// The page's own JS: re-render from the embedded data (binds interactivity;
// markup is identical to the baked HTML), log the visit, then refresh from
// the live RPCs so owners, photos and stats are current. Plain concatenation
// only — this string lives inside a template literal.
function pageScript(slug) {
  return `
    const SLUG = ${JSON.stringify(slug)};
    const SUPABASE_URL = ${JSON.stringify(API)};
    const SUPABASE_KEY = ${JSON.stringify(KEY)};
    const db = supabase.createClient(SUPABASE_URL, SUPABASE_KEY, { auth: { persistSession: false } });

    // First-party visit log — same shape and dedup as the dynamic /w/ page,
    // so Admin -> Traffic aggregates both under one per-model path.
    (function() {
      try {
        const params = new URLSearchParams(window.location.search);
        const utm_source = params.get('utm_source');
        const ref = document.referrer || null;
        const externalRef = ref && !ref.includes(window.location.hostname) ? ref : null;
        const effectiveSource = utm_source || (externalRef ? null : 'direct');
        const dedupKey = 'wristlog_visit_w_' + SLUG + '_' + (effectiveSource || '') + '_' + (params.get('utm_campaign') || '');
        const lastVisit = Number(localStorage.getItem(dedupKey) || 0);
        if (Date.now() - lastVisit < 1800000) return;
        localStorage.setItem(dedupKey, String(Date.now()));
        db.from('page_visits').insert({
          utm_source: effectiveSource, utm_medium: params.get('utm_medium'), utm_campaign: params.get('utm_campaign'),
          utm_content: params.get('utm_content'), utm_term: params.get('utm_term'),
          referrer: externalRef, path: '/w/?m=' + SLUG,
          user_agent: navigator.userAgent || null, user_id: null,
        }).then(() => {}).catch(() => {});
      } catch(e) {}
    })();

    const el = document.getElementById('model-page-content');
    let ctx = JSON.parse(document.getElementById('mp-data').textContent);
    const handlers = {
      back() { if (history.length > 1) history.back(); else location.href = 'https://wrotate.com'; },
      async share() {
        const url = location.href, title = ctx.m.brand + ' ' + ctx.m.name + ' on WRotate';
        if (navigator.share) { try { await navigator.share({ title: title, url: url }); } catch (e) {} }
        else { try { await navigator.clipboard.writeText(url); } catch (e) {} }
      },
      openPost(id) { if (id) location.href = '/p/?id=' + encodeURIComponent(id); },
      openProfile(uid, username) { if (username) location.href = '/profile/?u=' + encodeURIComponent(username); },
      openModel(id, slug) { if (slug) location.href = '/w/' + encodeURIComponent(slug) + '/'; },
      openApp() { location.href = 'https://wrotate.com'; },
      track(ev, props) { if (window.posthog) posthog.capture(ev, Object.assign({}, props, { surface: 'public' })); },
    };
    function render() { WRModelPage.render(el, ctx, handlers); }
    render();
    if (window.posthog) posthog.capture('model_page_viewed', { model_id: ctx.m.id, model: SLUG, brand: ctx.m.brand, surface: 'public' });

    (async function refresh() {
      try {
        const { data, error } = await db.rpc('model_page', { p_slug: SLUG });
        if (error || !data || !data.model) return;
        const m = data.model;
        const { data: st } = await db.rpc('model_stats', { p_model_id: m.id });
        ctx = { m: m, o: data.owners || { total_owners: 0, visible: [] }, st: st || {}, facts: data.teasers || [], loggedIn: false, publicMode: true };
        render();
      } catch (e) {}
    })();
  `;
}

// PostHog bootstrap — verbatim from w/index.html so analytics stay comparable.
const POSTHOG = readFileSync(join(root, 'w', 'index.html'), 'utf8')
