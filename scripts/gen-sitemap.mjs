let built = 0, skipped = 0;
const written = new Set();   // canonical slugs actually written (may differ from r.slug after a merge)
for (const r of bySlug) {
  let data;
  try {
    data = await rpc('model_page', { p_slug: r.slug });
  } catch (e) {
    throw new Error(`model_page(${r.slug}) failed — aborting so a transient API error can't ship a half-set: ${e.message}`);
  }
  if (!data || !data.model) { skipped++; continue; }   // merged/renamed since the SQL ran
  const m = data.model;
  let st = {};
  try { st = (await rpc('model_stats', { p_model_id: m.id })) || {}; }
  catch (e) { throw new Error(`model_stats(${r.slug}) failed: ${e.message}`); }
  const o = data.owners || {};
  // Strip member content from everything that gets committed (see header).
  const ctx = {
    m,
    o: { total_owners: o.total_owners || 0, era_min: o.era_min, era_max: o.era_max, visible: [] },
    st: { ...st, mine: [], photos: [], shots: [], visible: [] },
    facts: data.teasers || [],
    loggedIn: false, publicMode: true,
  };
  if (!/^[a-z0-9-]+$/.test(m.slug || '')) { skipped++; continue; }
  mkdirSync(join(root, 'w', m.slug), { recursive: true });
  writeFileSync(join(root, 'w', m.slug, 'index.html'), snapshotHtml(m.slug, ctx));
  written.add(m.slug);
  built++;
}

// Remove snapshots for models that dropped out (merged, un-enriched) — only
// dirs whose index.html carries the generation marker, never hand-made files.
const keep = written;
let removed = 0;
for (const d of readdirSync(join(root, 'w'), { withFileTypes: true })) {
  if (!d.isDirectory() || d.name === 'all' || keep.has(d.name)) continue;
  const p = join(root, 'w', d.name, 'index.html');
  if (existsSync(p) && readFileSync(p, 'utf8').includes(GEN_MARK)) {
    rmSync(join(root, 'w', d.name), { recursive: true });
    removed++;
  }
}

console.log(`sitemap.xml written: 5 static pages + ${rows.length} model pages · w/all/index.html written (${brands.size} brands) · ${built} snapshots built${skipped ? `, ${skipped} skipped (no longer resolve)` : ''}${removed ? `, ${removed} stale removed` : ''}`);
