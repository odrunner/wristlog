const SQL = `SELECT slug, brand, name,
    GREATEST(created_at, COALESCE(enriched_at, created_at))::date AS lastmod
  FROM watch_models
  WHERE merged_into IS NULL AND description IS NOT NULL AND hero_image IS NOT NULL
  ORDER BY brand, name`;

